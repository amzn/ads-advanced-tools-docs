"""Version resolution: deciding which copy of a record is current.

This module is the definition of correctness for the whole pipeline. Everything else moves
data around; this decides what the data *means*.

The rules, all from the delivery contract:

1. Records are identified by ``record_key``.
2. Among records sharing a key, the one with the highest ``streamBatch.version`` is
   current. Every lower version is superseded.
3. Arrival order carries no information. Notifications and deliveries can arrive out of
   order, so nothing may depend on the sequence in which rows were seen.
4. Metric values are totals, not increments. A current record replaces its predecessor
   rather than adding to it.
5. A delete marker is an ordinary record that happens to have all metrics null. It
   participates in version resolution exactly like any other, and wins if its version is
   highest. It is retained as a tombstone rather than removed, so that a later
   *lower*-version delivery cannot resurrect the record.
6. Equal versions are idempotent: reprocessing the same delivery must not change the
   result. So a tie leaves the existing row in place.

Rule 6 is the one that makes at-least-once delivery survivable at this layer, and it is
worth stating as a strict inequality in every implementation: ``>`` rather than ``>=``.
With ``>=``, replaying a batch rewrites rows for no reason, and any non-determinism in
which duplicate is chosen becomes visible in the output.

Implemented in pure Python so the rules are testable without a cluster. The equivalent
Spark ``MERGE INTO`` is generated by :func:`stream_staging.tables.sql.merge_current_sql`
from the same schema, and the end-to-end test drives this implementation.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping, MutableMapping, Sequence
from dataclasses import dataclass

from ..schema.model import DatasetSchema
from .deletes import IS_DELETED_COLUMN
from .record_key import RECORD_KEY_COLUMN

__all__ = [
    "ResolutionStats",
    "current_rows",
    "merge_into_state",
    "pick_current",
    "resolve_batch",
]


@dataclass(frozen=True)
class ResolutionStats:
    """What a resolution pass did.

    Emitted as metrics. The individual counts matter more than the total: a batch that is
    entirely ``superseded`` is a replay, and a batch that is entirely ``inserted`` on a
    populated table suggests the record key has changed — which is the failure mode a
    ``=``-based null-unsafe join produces.

    Attributes:
        inserted: Keys not previously present.
        updated: Keys replaced because the incoming version was higher.
        superseded: Incoming rows discarded because an equal or higher version was already
            held.
        deletes_applied: Rows that became tombstones in this pass.
        duplicates_within_batch: Rows discarded because a higher version for the same key
            appeared in the same batch.
    """

    inserted: int = 0
    updated: int = 0
    superseded: int = 0
    deletes_applied: int = 0
    duplicates_within_batch: int = 0

    @property
    def changed(self) -> int:
        """Rows that altered the current state."""
        return self.inserted + self.updated

    def as_metrics(self) -> dict[str, int]:
        """Return the counts in a form suitable for metric emission."""
        return {
            "rows_inserted": self.inserted,
            "rows_updated": self.updated,
            "rows_superseded": self.superseded,
            "deletes_applied": self.deletes_applied,
            "duplicates_within_batch": self.duplicates_within_batch,
        }


def pick_current(
    rows: Sequence[Mapping[str, object]],
    version_column: str,
) -> Mapping[str, object]:
    """Return the current row among rows sharing a record key.

    Args:
        rows: Rows with the same ``record_key``. Must be non-empty.
        version_column: Normalised column holding the batch version.

    Returns:
        The row with the highest version. On a tie the earliest in ``rows`` is returned,
        which keeps the choice deterministic; a tie means duplicate delivery of identical
        data, so the rows are interchangeable.

    Raises:
        ValueError: If ``rows`` is empty, or a row's version is null. A null version makes
            precedence undecidable, and guessing would silently pick a winner.
    """
    if not rows:
        raise ValueError("cannot pick a current row from an empty sequence")

    best: Mapping[str, object] | None = None
    best_version: int | None = None
    for row in rows:
        version = _require_version(row, version_column)
        if best_version is None or version > best_version:
            best, best_version = row, version
    assert best is not None  # guaranteed by the non-empty check above
    return best


def _require_version(row: Mapping[str, object], version_column: str) -> int:
    """Extract a row's batch version, rejecting absent or null values."""
    if version_column not in row:
        raise ValueError(
            f"row has no {version_column!r} column, so its precedence cannot be decided"
        )
    raw = row[version_column]
    if raw is None:
        raise ValueError(
            f"row has a null {version_column!r}. Version decides which copy of a record "
            "wins, so a null cannot be defaulted without silently choosing a winner"
        )
    if isinstance(raw, bool) or not isinstance(raw, int):
        raise ValueError(
            f"{version_column!r} must be an integer, got {type(raw).__name__}: {raw!r}"
        )
    return raw


def resolve_batch(
    rows: Iterable[Mapping[str, object]],
    schema: DatasetSchema,
) -> tuple[dict[str, Mapping[str, object]], int]:
    """Collapse a batch to one row per record key.

    Applied before touching existing state, for two reasons: a single batch routinely
    contains several versions of the same record, and reducing first means the merge
    handles one row per key instead of many.

    Args:
        rows: Normalised rows, each carrying ``record_key`` and the version column.
        schema: Declared dataset schema.

    Returns:
        A ``(by_key, duplicates_discarded)`` pair.

    Raises:
        ValueError: If a row lacks ``record_key``, or has an unusable version.
    """
    version_column = schema.version_column
    grouped: MutableMapping[str, list[Mapping[str, object]]] = {}
    total = 0

    for row in rows:
        total += 1
        key = row.get(RECORD_KEY_COLUMN)
        if not key:
            raise ValueError(
                f"row is missing {RECORD_KEY_COLUMN!r}. Identity is computed during "
                "normalisation, so a row without it has bypassed the transform layer"
            )
        grouped.setdefault(str(key), []).append(row)

    resolved = {
        key: pick_current(candidates, version_column) for key, candidates in grouped.items()
    }
    return resolved, total - len(resolved)


def merge_into_state(
    state: MutableMapping[str, Mapping[str, object]],
    incoming: Iterable[Mapping[str, object]],
    schema: DatasetSchema,
) -> ResolutionStats:
    """Merge a batch into existing state, in place.

    This is the reference form of the production ``MERGE INTO``. State is mutated so that
    a test can apply several batches in sequence and inspect the result after each, which
    is how out-of-order delivery is exercised.

    Args:
        state: Current rows keyed by ``record_key``. Mutated.
        incoming: Normalised rows from this batch.
        schema: Declared dataset schema.

    Returns:
        What the pass did.
    """
    version_column = schema.version_column
    batch, duplicates = resolve_batch(incoming, schema)

    inserted = updated = superseded = deletes_applied = 0

    for key, candidate in batch.items():
        candidate_version = _require_version(candidate, version_column)
        existing = state.get(key)

        if existing is None:
            state[key] = candidate
            inserted += 1
            if candidate.get(IS_DELETED_COLUMN):
                deletes_applied += 1
            continue

        existing_version = _require_version(existing, version_column)

        # Strictly greater, not greater-or-equal. Equality means the same delivery is being
        # processed again, and a replay must be a no-op.
        if candidate_version > existing_version:
            state[key] = candidate
            updated += 1
            if candidate.get(IS_DELETED_COLUMN) and not existing.get(IS_DELETED_COLUMN):
                deletes_applied += 1
        else:
            superseded += 1

    return ResolutionStats(
        inserted=inserted,
        updated=updated,
        superseded=superseded,
        deletes_applied=deletes_applied,
        duplicates_within_batch=duplicates,
    )


def current_rows(
    state: Mapping[str, Mapping[str, object]],
    *,
    include_deleted: bool = False,
) -> tuple[Mapping[str, object], ...]:
    """Return the current rows, tombstones excluded by default.

    This mirrors the view consumers query. Tombstones remain in the table so that version
    comparison stays possible, and are filtered on read rather than on write.

    Args:
        state: Current rows keyed by ``record_key``.
        include_deleted: When true, tombstones are included. Useful for auditing a mass
            delete, and wrong for reporting.

    Returns:
        Rows ordered by record key, for deterministic comparison in tests.
    """
    keys = sorted(state)
    if include_deleted:
        return tuple(state[key] for key in keys)
    return tuple(state[key] for key in keys if not state[key].get(IS_DELETED_COLUMN))
